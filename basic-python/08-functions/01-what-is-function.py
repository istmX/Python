# def is used to DEFINE a function
# A function is a reusable block of code that performs a specific task
# Functions help organize programs and avoid repeating code
# A function runs only when it is called, not when it is defined

def greet():
    # This code belongs to the function
    # It will execute whenever the function is called
    print("Hello")
    print("Welcome to Python")

# Calling the function
# Without this line, the function will NOT run
# The function can be reused many times in the same program
greet()

